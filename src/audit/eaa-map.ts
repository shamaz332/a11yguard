export function getEAAArticles(wcagCriteria: string[]): string[] {
  const articles: string[] = [];
  for (const criterion of wcagCriteria) {
    const mapped = eaaMap[criterion];
    if (mapped) articles.push(...mapped);
  }
  return [...new Set(articles)];
}
